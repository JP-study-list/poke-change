/**
 * gostring.js — 把交換清單變成 GO 遊戲內的搜尋字串
 *
 * 用途是把「想要」那一欄傳給對方，對方貼進自己的寶可夢搜尋框，
 * 一眼看出手上有沒有。搜尋只能搜自己的箱子，所以這串字對**收到的人**
 * 才有用，我們這邊產它、複製它，用的人是別人。
 *
 * ── 為什麼只給編號 ──
 * GO 的搜尋沒有括號，而且 `,`（或）綁得比 `&`（且）緊，
 * `25&異色,133` 會被讀成 `25 &（異色 或 133）`，不是「異色的皮卡丘或伊布」。
 * 所以「這隻要異色、那隻不用」這種混合條件**寫不出單一字串**。
 * 硬湊會產出一個似是而非、對方照著搜卻少東西的字串，那比沒有更糟。
 * 這裡只負責把對方的箱子從兩千隻縮到十幾隻，異色、XXL、背卡那些
 * 細節仍然看分享圖——圖本來就畫得出來，字串畫不出來。
 *
 * ── 為什麼會塌成一筆 ──
 * 同一隻的不同裝扮、不同背卡、不同條件在字串裡都是同一個編號。
 * 皮卡丘收了六格也只出現一次 25。這是對的：搜尋本來就指定不了是
 * 哪一個裝扮，而對方要做的事就是去翻自己所有的皮卡丘。
 *
 * ── 語言 ──
 * 純數字，三語通用，不必翻譯。之後要是加了條件（`異色&…`）就得
 * 分語言，那份對照在 `docs/go-search-syntax.md`。
 */

import { find } from "./dex.js";

/**
 * 字串長度的保守上限。
 *
 * 搜尋框確實有上限——社群的清箱工具會自動分段——但 Niantic 沒有
 * 公開數字，這個 200 是**還沒實測的保守值**，只拿來決定要不要多講
 * 一句提醒，不會真的把字串切掉。實測出真正的數字之後再調。
 *
 * 一欄可以收到 MAX_ITEMS（200）格，但去重之後常態是十幾個編號，
 * 碰得到這條線的是極少數，所以第一版不做分段介面。
 */
export const SEARCH_MAX = 200;

/**
 * 一欄的項目 → 去重、升序的圖鑑編號。
 *
 * 編號一律跟 `dex.js` 要，不從 id 字串拆。id 的形狀雖然是
 * `d150.fA`，但「名稱、圖片、屬性一律以圖鑑為準」這條也涵蓋編號，
 * 自己解析等於多開一個會跟圖鑑講不同話的來源。
 *
 * 查不到條目的紀錄直接跳過，跟格子牆同一個做法：圖鑑更新拿掉某個 id
 * 之後，畫面上畫不出那一格，字串裡也不該冒出一個編號。
 */
export function dexNumbers(items) {
  const seen = new Set();
  for (const it of items || []) {
    const e = it && find(it.id);
    if (e && e.dex) seen.add(e.dex);
  }
  return [...seen].sort((a, b) => a - b);
}

/**
 * 一欄的項目 → 搜尋字串。空的就回空字串（呼叫端自己決定要不要畫鈕）。
 */
export function searchString(items) {
  return dexNumbers(items).join(",");
}
